import { WebSocket } from "ws";
const [port, url] = process.argv.slice(2);
const created = await (await fetch(`http://127.0.0.1:${port}/json/new?${encodeURIComponent(url)}`, { method: "PUT" })).json();
const ws = new WebSocket(created.webSocketDebuggerUrl);
let id = 0; const pending = new Map();
ws.on("message", (d) => { const m = JSON.parse(String(d)); if (m.id && pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id); } });
await new Promise((r) => ws.once("open", r));
const send = (m, p = {}) => new Promise((res) => { const n = ++id; pending.set(n, res); ws.send(JSON.stringify({ id: n, method: m, params: p })); });
const evaluate = async (e) => (await send("Runtime.evaluate", { expression: e, awaitPromise: true, returnByValue: true })).result?.result?.value;
await send("Runtime.enable");
await new Promise((r) => setTimeout(r, 2500));
const before = await evaluate(`(() => { try { return { readable: true, keys: Object.keys(localStorage), test: (localStorage.setItem('__probe','1'), localStorage.getItem('__probe')) }; } catch (e) { return { readable: false, err: String(e) }; } })()`);
console.log("before:", JSON.stringify(before));
await evaluate(`document.querySelector('.theme-trigger')?.click()`);
await new Promise((r) => setTimeout(r, 400));
await evaluate(`[...document.querySelectorAll('.theme-picker button')].find(b=>/iPod/.test(b.textContent))?.click()`);
await new Promise((r) => setTimeout(r, 1200));
const after = await evaluate(`({ keys: Object.keys(localStorage), themeAttr: document.querySelector('.radio-root')?.dataset.theme, profile: localStorage.getItem('qiaomu-radio-profile-v1')?.slice(0,60), theme: localStorage.getItem('qiaomu-radio-theme-v2') })`);
console.log("after:", JSON.stringify(after));
ws.close();
